"""Generates the finger-soccer team table (lib/games/finger_soccer/core/bm_data.dart, between the GEN markers) and the
nx_catalog SQL rows from docs/fs_teams_map.py (the owner's 77 NX pucks). Prices follow gem_shop.dart defaultTeamPrice.
Usage: python3 tool/gen_fs_pucks.py dart|sql"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'docs'))
from fs_teams_map import TEAMS, FREE, CATS


def price(t):
    if t[0] in FREE:
        return 0
    s = min(20, max(9, t[5] + t[6]))
    return round((150 + (s - 9) * 350 / 11) / 10) * 10


def dart():
    out = ['const List<List<Object>> kBmCats = <List<Object>>[']
    for c in CATS:
        out.append(f"  <Object>['{c[0]}', '{c[1]}', '{c[2]}'],")
    out.append('];')
    out.append('')
    out.append('/// Every fieldable piece set: the owner\'s NX pucks (docs/fs_teams_map.py, generated by tool/gen_fs_pucks.py).')
    out.append('/// [BmTeamDef.art] is the iso cut-out; the art is shown exactly as cut, never framed or recoloured.')
    out.append('const List<BmTeamDef> kBmTeamDefs = <BmTeamDef>[')
    for t in TEAMS:
        out.append(f"  BmTeamDef('{t[0]}', '{t[1]}', '{t[2]}', '{t[3]}', '{kPuck}{t[0]}.webp', {t[5]}, {t[6]}),")
    out.append("  // Not a team: the lobby's \"create your custom team\" tile (1000 gems, then a photo). The shared custom teams")
    out.append("  // themselves (cx_<hex>, power 10) are appended to kBmTeams at runtime by FsCustomTeams.")
    out.append(f"  BmTeamDef('custom_team', 'custom', 'Create Custom Team', 'ساخت تیم اختصاصی', '{kPuck}fx_crown.webp', 10, 10),")
    out.append('];')
    return '\n'.join(out)


kPuck = 'assets/games/finger_soccer/pucks/iso/'


def sql():
    rows = []
    for t in TEAMS:
        nm = t[2].replace("'", "''")
        rows.append(f"  ('fs_team:{t[0]}', {price(t)}, 'gems', 'team', '{nm}', '{t[1]}', true)")
    return ',\n'.join(rows)


if __name__ == '__main__':
    print(dart() if sys.argv[1] == 'dart' else sql())
